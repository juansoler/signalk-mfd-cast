"use strict";

/**
 * go2rtc supervisor.
 *
 * go2rtc repacketises RTSP into WebRTC without touching the video: that is the
 * whole reason this plugin can run on a busy Raspberry Pi. The plugin owns the
 * process, its config file and its API; the browser only ever talks to the
 * plugin (the SDP exchange is proxied).
 */

const fs = require("fs");
const path = require("path");
const { spawn } = require("child_process");

const LOG_LIMIT = 120;
const START_TIMEOUT_MS = 15000;

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function binaryName(platform = process.platform) {
  return platform === "win32" ? "go2rtc.exe" : "go2rtc";
}

/**
 * Resolves the go2rtc binary: explicit path, then the plugin data dir, then a
 * bare command resolved through PATH.
 */
function resolveBinary({ configured, dataDir, platform = process.platform, exists = fs.existsSync } = {}) {
  const name = binaryName(platform);
  const explicit = String(configured || "").trim();

  if (explicit && !explicit.includes("/") && !explicit.includes("\\")) {
    return explicit; // bare command, spawn resolves it through PATH
  }
  if (explicit && exists(explicit)) return explicit;
  if (dataDir) {
    const bundled = path.join(dataDir, "bin", name);
    if (exists(bundled)) return bundled;
  }
  return null;
}

function yamlValue(value) {
  // JSON strings are valid YAML double-quoted scalars for our simple values.
  return JSON.stringify(String(value));
}

/** Minimal go2rtc.yaml: API and RTSP bound to loopback, WebRTC on the LAN. */
function buildConfigYaml({ apiPort = 1984, webrtcPort = 8555, rtspPort = 8554, streams = {} } = {}) {
  const lines = [
    "# generated by signalk-mfd-cast",
    "api:",
    `  listen: ${yamlValue(`127.0.0.1:${apiPort}`)}`,
    "rtsp:",
    `  listen: ${yamlValue(`127.0.0.1:${rtspPort}`)}`,
    "webrtc:",
    `  listen: ${yamlValue(`:${webrtcPort}`)}`,
    "log:",
    "  level: info",
    "  format: text",
  ];

  // Config-defined sources are trusted by go2rtc, unlike API-added exec/echo
  // sources, which are rejected as "insecure". Demo mode relies on this.
  const entries = Object.entries(streams || {});
  if (entries.length > 0) {
    lines.push("streams:");
    for (const [name, source] of entries) {
      lines.push(`  ${name}: ${yamlValue(source)}`);
    }
  }

  return `${lines.join("\n")}\n`;
}

class Go2rtc {
  constructor({
    binary,
    dataDir,
    apiPort = 1984,
    webrtcPort = 8555,
    nice = 10,
    log = () => {},
    platform = process.platform,
    spawnImpl = spawn,
    fetchImpl = globalThis.fetch,
    sleepImpl = sleep,
    now = Date.now,
  } = {}) {
    if (!binary) throw new Error("go2rtc binary is required");
    if (!dataDir) throw new Error("go2rtc data directory is required");

    this.binary = binary;
    this.dataDir = dataDir;
    this.apiPort = Number(apiPort) || 1984;
    this.webrtcPort = Number(webrtcPort) || 8555;
    this.nice = Number(nice) || 0;
    this.log = log;
    this.platform = platform;
    this.spawnImpl = spawnImpl;
    this.fetchImpl = fetchImpl;
    this.sleep = sleepImpl;
    this.now = now;

    this.child = null;
    this.lines = [];
    this.stopping = false;
    this.configPath = path.join(dataDir, "go2rtc.yaml");
    this.configStreams = {};
    this.runningSignature = null;
  }

  /**
   * Declares streams that must exist in the generated YAML (trusted sources).
   *
   * Changing them forces the next start() to restart the process, because
   * go2rtc only accepts exec/echo sources from its config file.
   */
  setConfigStreams(streams = {}) {
    this.configStreams = { ...streams };
  }

  get endpoint() {
    return `http://127.0.0.1:${this.apiPort}`;
  }

  get pid() {
    return this.child && this.child.pid ? this.child.pid : null;
  }

  get running() {
    return Boolean(this.child) && !this.stopping;
  }

  pushLine(channel, chunk) {
    const text = String(chunk).replace(/\r/g, "");
    for (const line of text.split("\n")) {
      const trimmed = line.trimEnd();
      if (!trimmed) continue;
      this.lines.push(`[${channel}] ${trimmed}`);
      if (this.lines.length > LOG_LIMIT) this.lines.splice(0, this.lines.length - LOG_LIMIT);
    }
  }

  logTail(count = 25) {
    return this.lines.slice(-count);
  }

  writeConfig() {
    fs.mkdirSync(this.dataDir, { recursive: true });
    fs.writeFileSync(
      this.configPath,
      buildConfigYaml({
        apiPort: this.apiPort,
        webrtcPort: this.webrtcPort,
        streams: this.configStreams,
      }),
      "utf8"
    );
  }

  async start() {
    const signature = JSON.stringify(this.configStreams || {});
    if (this.running && signature === this.runningSignature) return this;
    if (this.running) await this.stop();

    this.writeConfig();
    this.stopping = false;

    const args = ["-config", this.configPath];
    const useNice = this.nice > 0 && this.platform !== "win32";
    const command = useNice ? "nice" : this.binary;
    const commandArgs = useNice ? ["-n", String(this.nice), this.binary, ...args] : args;

    this.log(`starting go2rtc: ${command} ${commandArgs.join(" ")}`);
    this.child = this.spawnImpl(command, commandArgs, {
      windowsHide: true,
      stdio: ["ignore", "pipe", "pipe"],
    });

    if (this.child.stdout) this.child.stdout.on("data", (chunk) => this.pushLine("out", chunk));
    if (this.child.stderr) this.child.stderr.on("data", (chunk) => this.pushLine("err", chunk));

    let exited = false;
    this.child.on("exit", (code, signal) => {
      exited = true;
      this.log(`go2rtc exited (code=${code} signal=${signal || "none"})`);
      this.child = null;
    });
    this.child.on("error", (error) => {
      exited = true;
      this.pushLine("err", error.message);
      this.log(`go2rtc spawn error: ${error.message}`);
    });

    const deadline = this.now() + START_TIMEOUT_MS;
    while (this.now() < deadline) {
      if (exited) {
        throw new Error(`go2rtc no arrancó: ${this.logTail(3).join(" | ") || "sin salida"}`);
      }
      try {
        const response = await this.request("/api/streams", { method: "GET", timeoutMs: 1500 });
        if (response.ok) {
          this.runningSignature = signature;
          this.log(`go2rtc listo en ${this.endpoint}`);
          return this;
        }
      } catch (_error) {
        // Not listening yet.
      }
      await this.sleep(200);
    }

    await this.stop();
    throw new Error(`go2rtc no respondió en ${START_TIMEOUT_MS / 1000}s`);
  }

  async stop() {
    const child = this.child;
    if (!child) return;
    this.stopping = true;
    this.log("stopping go2rtc");

    const done = new Promise((resolve) => {
      let settled = false;
      let timer = null;
      const finish = () => {
        if (settled) return;
        settled = true;
        if (timer) clearTimeout(timer);
        resolve();
      };
      child.once("exit", finish);
      timer = setTimeout(finish, 3000);
    });

    try {
      child.kill("SIGTERM");
    } catch (_error) {
      // already gone
    }
    await done;

    if (this.child) {
      try {
        this.child.kill("SIGKILL");
      } catch (_error) {
        // already gone
      }
    }
    this.child = null;
    this.stopping = false;
    this.runningSignature = null;
  }

  async request(pathname, { method = "GET", body, headers, timeoutMs = 8000, raw = false } = {}) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeoutMs);
    try {
      const response = await this.fetchImpl(`${this.endpoint}${pathname}`, {
        method,
        body,
        headers,
        signal: controller.signal,
      });
      if (!raw) {
        const text = await response.text();
        let data = null;
        if (text) {
          try {
            data = JSON.parse(text);
          } catch (_error) {
            data = text;
          }
        }
        return { ok: response.ok, status: response.status, data, text };
      }
      return response;
    } finally {
      clearTimeout(timer);
    }
  }

  /** Adds or replaces a stream; go2rtc persists it into the generated YAML. */
  async setStream(name, source) {
    if (!source) throw new Error("stream source is required");
    const query = `?name=${encodeURIComponent(name)}&src=${encodeURIComponent(source)}`;
    const result = await this.request(`/api/streams${query}`, { method: "PUT" });
    if (!result.ok) {
      const detail = String(result.text || "").trim().slice(0, 200);
      throw new Error(
        `go2rtc rechazó el stream (HTTP ${result.status})${detail ? `: ${detail}` : ""}`
      );
    }
    this.log(`stream ${name} => ${source.replace(/#.*$/, "")}`);
    return result;
  }

  async deleteStream(name) {
    const query = `?src=${encodeURIComponent(name)}`;
    try {
      await this.request(`/api/streams${query}`, { method: "DELETE" });
    } catch (_error) {
      // Deleting a stream that does not exist is not an error for us.
    }
  }

  async streams() {
    const result = await this.request("/api/streams");
    return result.ok && result.data && typeof result.data === "object" ? result.data : {};
  }

  /**
   * Relays a browser SDP offer to go2rtc and returns the answer SDP.
   *
   * Keeping the exchange server-side means the browser never needs to reach the
   * go2rtc API port, which stays bound to loopback.
   */
  async webrtc(name, offerSdp) {
    const result = await this.request(`/api/webrtc?src=${encodeURIComponent(name)}`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ type: "offer", sdp: offerSdp }),
      timeoutMs: 15000,
    });
    if (!result.ok) {
      throw new Error(`go2rtc WebRTC falló (HTTP ${result.status})`);
    }
    if (result.data && typeof result.data === "object" && result.data.sdp) {
      return String(result.data.sdp);
    }
    if (typeof result.data === "string" && result.data.includes("v=0")) {
      return result.data;
    }
    throw new Error("go2rtc devolvió una respuesta WebRTC vacía");
  }
}

module.exports = {
  Go2rtc,
  START_TIMEOUT_MS,
  binaryName,
  buildConfigYaml,
  resolveBinary,
};
